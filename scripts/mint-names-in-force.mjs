// mint-names-in-force.mjs — derive the `CLEAROTRON_*` names this build reads, and write them to
// shared/names-in-force.mjs.
//
// ── WHY THIS IS DERIVED AND NOT WRITTEN BY HAND ──────────────────────────────────────────────────
//
// It is the replacement half of the retired-spelling check (tracker issue 168). The DETECTION half
// needs nothing from this file: no product code reads a `PRELIM_*` name any more, so a `PRELIM_*` that
// is set is dead whatever this list says. What the list decides is the second half of the sentence —
// which name to tell the operator to use instead — and that is where a hand list does damage. A hand
// list stops at whoever was looking, and sending an operator to a variable nothing reads replaces one
// silent failure with another.
//
// The rule is the rename's own: the sweep moved `PRELIM_<SUFFIX>` to `CLEAROTRON_<SUFFIX>`, suffix
// untouched. So every `CLEAROTRON_<SUFFIX>` this build reads implies `PRELIM_<SUFFIX>` was its old
// spelling, and a `PRELIM_*` name with no `CLEAROTRON_` partner is a setting that no longer exists at
// all rather than one that moved. Both are worth saying and they are different sentences.
//
// ── THE ORACLE THIS DERIVATION IS CHECKED AGAINST ────────────────────────────────────────────────
//
// A derivation that is only ever compared against itself proves nothing, which is the shape this repo
// keeps paying for. So the arm in driver/test/retired-env-spellings.test.mjs holds this output to the
// THIRTEEN dead names Cart measured in the production install's own env file on 2026-09-05 — a
// population this script never saw and cannot influence. All thirteen must resolve to a replacement.
// If a future sweep breaks the suffix rule, that arm reds on real-world data rather than on a
// restatement of this code.
//
// Usage:  node scripts/mint-names-in-force.mjs [--check]
//   --check  exit 1 if the committed file disagrees with a fresh derivation, printing the difference

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(REPO, "shared", "names-in-force.mjs");

/**
 * Files whose `CLEAROTRON_*` mentions count as a read.
 *
 * TEST CODE IS EXCLUDED AND THAT IS THE POINT: a test may set any name it likes to drive a fixture,
 * and a name only a test mentions is not a name this build reads. Including them would mint
 * replacements for settings the product does not have. `.js` and `.ts` are in with `.mjs` because
 * the providers' own `src` directories carry non-test `.js` — a `.mjs`-only derivation has produced
 * wrong answers on this tree before (tracker issue 96).
 */
export function sourceFiles(root = REPO) {
  const tracked = execFileSync("git", ["-C", root, "ls-files", "*.mjs", "*.js", "*.ts"], {
    encoding: "utf8", maxBuffer: 64 * 1024 * 1024,
  }).split("\n").filter(Boolean);
  return tracked.filter((f) => !/(^|\/)(test|tests|bench)\//.test(f) && !/\.test\.(mjs|ts|js)$/.test(f));
}

const NAME_RE = /\bCLEAROTRON_[A-Z0-9_]+/g;

/** Every `CLEAROTRON_*` name mentioned by non-test source, sorted. */
export function deriveNamesInForce(root = REPO) {
  const found = new Set();
  for (const rel of sourceFiles(root)) {
    let text;
    // A file that cannot be read is a could-not-look, not an empty file. It must not silently
    // shrink the list — a missing name here becomes "this setting no longer exists at all", which
    // is a confident wrong sentence to an operator.
    try { text = readFileSync(join(root, rel), "utf8"); }
    catch (e) { throw new Error(`mint-names-in-force: cannot read ${rel}: ${e.message}`); }
    for (const m of text.matchAll(NAME_RE)) found.add(m[0]);
  }
  return [...found].sort();
}

function render(names) {
  return `// SPDX-License-Identifier: AGPL-3.0-only
// Copyright 2026 Cordillera Sàrl. Additional terms under section 7 of the AGPL-3.0 apply — see ADDITIONAL-TERMS.md
// names-in-force.mjs — GENERATED by scripts/mint-names-in-force.mjs. Do not edit by hand.
//
// Every \`CLEAROTRON_*\` name this build reads. It exists so the retired-spelling check can name the
// replacement for an old \`PRELIM_*\` line rather than only saying the old one is dead — see
// shared/env-aliases.mjs and tracker issue 168. Re-mint with:
//
//   node scripts/mint-names-in-force.mjs
//
// driver/test/retired-env-spellings.test.mjs regenerates this and refuses a stale copy.

export const NAMES_IN_FORCE = Object.freeze([
${names.map((n) => `  "${n}",`).join("\n")}
]);
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const names = deriveNamesInForce();
  const next = render(names);
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT, "utf8"); }
    catch { console.error(`mint-names-in-force: ${OUT} is missing — run without --check to mint it.`); process.exit(1); }
    if (current === next) { console.log(`names-in-force: current, ${names.length} name(s).`); process.exit(0); }
    const had = new Set([...current.matchAll(/"(CLEAROTRON_[A-Z0-9_]+)"/g)].map((m) => m[1]));
    const now = new Set(names);
    const added = names.filter((n) => !had.has(n));
    const gone = [...had].filter((n) => !now.has(n));
    console.error(`names-in-force: STALE. ${added.length} added, ${gone.length} removed.`);
    for (const n of added) console.error(`  + ${n}`);
    for (const n of gone) console.error(`  - ${n}`);
    console.error(`\nRe-mint: node scripts/mint-names-in-force.mjs`);
    process.exit(1);
  }
  writeFileSync(OUT, next);
  console.log(`names-in-force: wrote ${names.length} name(s) to shared/names-in-force.mjs`);
}
